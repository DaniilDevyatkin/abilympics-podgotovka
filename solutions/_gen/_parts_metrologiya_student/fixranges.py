data = json.load(open(PATH, encoding="utf-8"))
used = set()
for t in data["tasks"]:
    for a in t["actions"]:
        for s in a["steps"]:
            for k in ("do", "why", "check", "fail", "expert"):
                key = (s["n"], k)
                if key in SUF:
                    assert not s[k].rstrip().endswith(SUF[key]), key
                    s[k] = s[k].rstrip() + " " + SUF[key]
                    used.add(key)

missing = set(SUF) - used
if missing:
    raise SystemExit("не найдены шаги: %s" % sorted(missing))

json.dump(data, open(PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

