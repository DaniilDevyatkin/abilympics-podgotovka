    for a in t["actions"]:
        for s in a["steps"]:
            steps += 1
            for k, (lo, hi) in lim.items():
                chars += len(s[k])
                if not lo <= len(s[k]) <= hi:
                    bad.append(f'{s["n"]} {k}={len(s[k])}')
